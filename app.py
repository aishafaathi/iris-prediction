
from flask import Flask, render_template, request, send_from_directory
from pathlib import Path
import pickle
import csv

app = Flask(__name__)

# Get the directory containing this file
BASE_DIR = Path(__file__).resolve().parent
RESULTS_DIR = BASE_DIR / "results"


# Load the trained model and scaler
with open(BASE_DIR / "model.pkl", "rb") as f:
    model = pickle.load(f)

with open(BASE_DIR / "scaler.pkl", "rb") as f:
    scaler = pickle.load(f)


@app.route("/")
def home():
    return render_template("index.html")


@app.route("/predict", methods=["POST"])
def predict():
    try:
        # Read the flower measurements
        sepal_length = float(request.form["sepal_length"])
        sepal_width = float(request.form["sepal_width"])
        petal_length = float(request.form["petal_length"])
        petal_width = float(request.form["petal_width"])

        # Validate the input
        features = [[
            sepal_length,
            sepal_width,
            petal_length,
            petal_width
        ]]

        if any(value <= 0 for value in features[0]):
            raise ValueError("Measurements must be positive.")

        # Scale the input and predict
        features_scaled = scaler.transform(features)
        prediction = model.predict(features_scaled)[0]

        # Support numeric or string class labels
        flower_names = {
            0: "Setosa",
            1: "Versicolor",
            2: "Virginica",
            "0": "Setosa",
            "1": "Versicolor",
            "2": "Virginica",
            "setosa": "Setosa",
            "versicolor": "Versicolor",
            "virginica": "Virginica",
        }

        prediction_value = (
            prediction.item()
            if hasattr(prediction, "item")
            else prediction
        )

        result = flower_names.get(prediction_value)

        if result is None:
            result = str(prediction_value)

        return render_template(
            "index.html",
            prediction=result
        )

    except (ValueError, KeyError):
        return render_template(
            "index.html",
            error="Please enter valid positive numerical measurements."
        ), 400


@app.route("/comparison")
def comparison():
    # Read model comparison results generated by model.py
    csv_path = BASE_DIR / "model_comparison.csv"
    results = []

    if csv_path.exists():
        with open(csv_path, newline="", encoding="utf-8") as file:
            results = list(csv.DictReader(file))

    return render_template(
        "comparison.html",
        results=results,
        chart_exists=(RESULTS_DIR / "model_comparison.png").is_file(),
        matrix_exists=(RESULTS_DIR / "confusion_matrix.png").is_file(),
    )


@app.route("/results/<path:filename>")
def result_file(filename):
    # Serve generated model evaluation graphs
    return send_from_directory(RESULTS_DIR, filename)


# Local development only; Vercel imports the app instance above.
if __name__ == "__main__":
    app.run(debug=True)
